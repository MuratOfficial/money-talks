/**
 * Профиль по доле самых рискованных ответов в тесте: пять равных диапазонов
 * по 20%. Раньше профилей было четыре (с «Сбалансированным»), поэтому для
 * сохранённых результатов название тоже пересчитывается по проценту.
 */
export function riskProfileByPercentage(percentage: number): RiskProfileInfo {
  const index = Math.min(RISK_PROFILES.length - 1, Math.max(0, Math.floor((Number(percentage) || 0) / 20)));
  return RISK_PROFILES[index];
}

/** «80% — депозиты, облигации, НСЖ; 20% — индексные ETF, золото». */
export function allocationText(profile: RiskProfileInfo): string {
  return `${profile.protectiveShare}% — ${profile.protectiveAssets}; ${100 - profile.protectiveShare}% — ${profile.growthAssets}`;
}
