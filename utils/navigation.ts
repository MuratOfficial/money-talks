import { router, type Href } from 'expo-router';

/**
 * Уйти на предыдущий экран. Если истории нет (открыли по ссылке или зашли
 * сразу в раздел) — отправляем на заданный экран, чтобы не остаться в тупике.
 *
 * Раньше все «назад» в приложении делались через router.replace: при Slot
 * истории не было вовсе, и разницы не чувствовалось. С обычным Stack replace
 * подменяет текущий экран в стеке, и системная кнопка «Назад» уводила совсем
 * не туда — например с «Активов» в «ЛФП».
 */
export function goBack(fallback: Href) {
  if (router.canGoBack()) {
    router.back();
    return;
  }
  router.replace(fallback);
}
